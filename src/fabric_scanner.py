def _serpentine_indices(rows: int, cols: int):
    for row in range(rows):
        col_range = range(cols) if row % 2 == 0 else range(cols - 1, -1, -1)
        for col in col_range:
            yield row, col


def _normalize_palette(palette) -> list[tuple[float, float, float, float]]:
    if palette is None:
        return list(SWATCH_PALETTE)
    if isinstance(palette, np.ndarray):
        palette = palette.tolist()
    if (
        isinstance(palette, (list, tuple))
        and len(palette) >= 3
        and all(isinstance(v, (int, float, np.integer, np.floating)) for v in palette[:3])
    ):
        r, g, b = [float(v) for v in palette[:3]]
        a = float(palette[3]) if len(palette) > 3 else 1.0
        return [(r, g, b, a)]

    colors = []
    for color in palette or []:
        if isinstance(color, np.ndarray):
            color = color.tolist()
        if not isinstance(color, (list, tuple)) or len(color) < 3:
            continue
        r, g, b = [float(v) for v in color[:3]]
        a = float(color[3]) if len(color) > 3 else 1.0
        colors.append((r, g, b, a))
    return colors or list(SWATCH_PALETTE)


def _normalize_batch_display_colors(colors, count: int) -> list[tuple[float, float, float, float]] | None:
    if colors is None:
        return None
    normalized: list[tuple[float, float, float, float]] = []
    for color in colors:
        if isinstance(color, np.ndarray):
            color = color.tolist()
        if not isinstance(color, (list, tuple)) or len(color) < 3:
            continue
        rgb = [float(color[i]) for i in range(3)]
        if max(rgb) > 1.0:
            rgb = [v / 255.0 for v in rgb]
        alpha = float(color[3]) if len(color) > 3 else 1.0
        normalized.append((
            float(np.clip(rgb[0], 0.0, 1.0)),
            float(np.clip(rgb[1], 0.0, 1.0)),
            float(np.clip(rgb[2], 0.0, 1.0)),
            float(np.clip(alpha, 0.0, 1.0)),
        ))
        if len(normalized) >= count:
            break
    return normalized or None


