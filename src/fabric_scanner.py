def _perspective_coeffs(dst_points, src_points):
    matrix = []
    vector = []
    for (x, y), (u, v) in zip(dst_points, src_points):
        matrix.append([x, y, 1.0, 0.0, 0.0, 0.0, -u * x, -u * y])
        matrix.append([0.0, 0.0, 0.0, x, y, 1.0, -v * x, -v * y])
        vector.extend([u, v])
    return np.linalg.solve(np.asarray(matrix, dtype=float), np.asarray(vector, dtype=float)).tolist()


def _materialize_texture(texture, max_dim=None):
    """Accepts a PIL image, or a lazy tiled-texture descriptor from the GUI.

    Scan Mode hands over one seamless period tile plus its repeat counts rather
    than a fully glued image -- the glued form is exact integer repetition, so
    at 64 repeats it is hundreds of MB holding a couple of hundred KB of real
    content. Asking it for `max_dim` stamps the tile out at that size.
    """
    if texture is None:
        return None
    rasterize = getattr(texture, "rasterize", None)
    if rasterize is None:
        return texture
    return rasterize(max_dim)


def _paste_projected_texture(base: Image.Image, texture, projected_quad) -> bool:
    if any(point is None for point in projected_quad):
        return False
    dst = [(float(point[0]), float(point[1])) for point in projected_quad]
    # Deliberately materialised at full resolution rather than at the quad's
    # on-screen size. Pre-filtering the source to roughly what the warp can
    # resolve is cheaper and, judged on its own, cleaner -- Image.transform
    # point-samples with a bicubic kernel and does not area-average, so a large
    # source aliases. But it changes the captured pixels (measured: ~13% of them
    # by more than 8/255 at a 2x pre-filter), and these captures are the
    # scanner's output data. Full resolution keeps every saved image identical
    # to what the glued-image pipeline produced. The memory win is unaffected:
    # this is one transient rasterisation per capture instead of a permanently
    # held glued image per cell.
    texture = _materialize_texture(texture, None)
    src = texture.convert("RGB")
    src_w, src_h = src.size
    if src_w <= 1 or src_h <= 1:
        return False
    src_quad = [(0.0, 0.0), (float(src_w), 0.0), (float(src_w), float(src_h)), (0.0, float(src_h))]
    try:
        coeffs = _perspective_coeffs(dst, src_quad)
    except np.linalg.LinAlgError:
        return False
    resample = getattr(getattr(Image, "Resampling", Image), "BICUBIC", Image.BICUBIC)
    warped = src.transform(base.size, Image.Transform.PERSPECTIVE, coeffs, resample=resample)
    mask_src = Image.new("L", (src_w, src_h), 255)
    mask = mask_src.transform(base.size, Image.Transform.PERSPECTIVE, coeffs, resample=resample)
    base.paste(warped, (0, 0), mask)
    return True


def _trim_rendered_texture(texture: Image.Image) -> Image.Image:
    texture = texture.convert("RGB")
    arr = np.asarray(texture, dtype=np.uint8)
    if arr.size == 0:
        return texture
    edge = np.concatenate([
        arr[:4, :, :].reshape(-1, 3),
        arr[-4:, :, :].reshape(-1, 3),
        arr[:, :4, :].reshape(-1, 3),
        arr[:, -4:, :].reshape(-1, 3),
    ])
    bg = np.median(edge, axis=0)
    diff = np.linalg.norm(arr.astype(np.float32) - bg.astype(np.float32), axis=2)
    mask = (diff > 14.0) | (arr.max(axis=2) > 55)
    ys, xs = np.where(mask)
    if xs.size < 16 or ys.size < 16:
        return texture
    pad = 0
    x0 = max(0, int(xs.min()) - pad)
    x1 = min(texture.size[0], int(xs.max()) + pad + 1)
    y0 = max(0, int(ys.min()) - pad)
    y1 = min(texture.size[1], int(ys.max()) + pad + 1)
    return texture.crop((x0, y0, x1, y1))


def _tile_rendered_texture(
    texture: Image.Image,
    repeat_rows: int,
    repeat_cols: int,
    spacing_x: float = 1.0,
    spacing_y: float = 1.0,
) -> Image.Image:
    repeat_rows = max(1, int(repeat_rows))
    repeat_cols = max(1, int(repeat_cols))
    spacing_x = float(np.clip(float(spacing_x), 0.55, 1.45))
    spacing_y = float(np.clip(float(spacing_y), 0.55, 1.45))
    tile = _trim_rendered_texture(texture)
    tile_w, tile_h = tile.size
    if tile_w <= 1 or tile_h <= 1:
        return tile
    max_dim = 2048
    step_w = max(1, int(round(tile_w * spacing_x)))
    step_h = max(1, int(round(tile_h * spacing_y)))
    canvas_w = step_w * (repeat_cols - 1) + tile_w
    canvas_h = step_h * (repeat_rows - 1) + tile_h
    scale = min(1.0, max_dim / max(float(canvas_w), 1.0), max_dim / max(float(canvas_h), 1.0))
    if scale < 1.0:
        resample = getattr(getattr(Image, "Resampling", Image), "LANCZOS", Image.LANCZOS)
        tile = tile.resize((max(1, int(tile_w * scale)), max(1, int(tile_h * scale))), resample)
        tile_w, tile_h = tile.size
        step_w = max(1, int(round(tile_w * spacing_x)))
        step_h = max(1, int(round(tile_h * spacing_y)))
    canvas_w = step_w * (repeat_cols - 1) + tile_w
    canvas_h = step_h * (repeat_rows - 1) + tile_h
    canvas = Image.new("RGB", (canvas_w, canvas_h), (18, 22, 28))
    for r in range(repeat_rows):
        for c in range(repeat_cols):
            canvas.paste(tile, (c * step_w, r * step_h))
    return canvas


def _render_cell_pattern_texture(plan: FabricPlan, row: int, col: int, width: int = 420, height: int = 340) -> Image.Image:
    """Render one knitted fabric sample before image-based repetition."""
    from PIL import ImageDraw

    scale = 3
    width = max(96, int(width))
    height = max(80, int(height))
    canvas = Image.new("RGB", (width * scale, height * scale), (18, 23, 31))
    draw = ImageDraw.Draw(canvas)
    colors = _cell_color_set(plan, row, col)
    curves = _smoothed_cell_model_curves(plan, row, col)
    if not curves:
        return canvas.resize((width, height), getattr(getattr(Image, "Resampling", Image), "LANCZOS", Image.LANCZOS))

    all_pts = np.vstack([curve[:, :2] for curve in curves if len(curve) > 1])
    min_xy = all_pts.min(axis=0)
    max_xy = all_pts.max(axis=0)
    center = (min_xy + max_xy) * 0.5
    span = np.maximum(max_xy - min_xy, 1e-6)
    usable_w = width * scale * 0.84
    usable_h = height * scale * 0.84
    px_scale = min(usable_w / float(span[0]), usable_h / float(span[1]))
    origin = np.array([width * scale * 0.5, height * scale * 0.5], dtype=np.float32)
    line_w = max(2, int(min(width, height) * scale * 0.030))
    shade_w = max(line_w + 2, int(line_w * 1.65))

    for curve_idx, curve in enumerate(curves):
        if len(curve) < 2:
            continue
        rgba = colors[curve_idx % len(colors)]
        color = tuple(int(255 * float(v)) for v in rgba[:3])
        shadow = tuple(max(0, int(channel * 0.32)) for channel in color)
        highlight = tuple(min(255, int(channel * 1.18 + 18)) for channel in color)
        pts = [
            (
                int(round(origin[0] + (float(p[0]) - center[0]) * px_scale)),
                int(round(origin[1] - (float(p[1]) - center[1]) * px_scale)),
            )
            for p in curve
        ]
        draw.line(pts, fill=shadow, width=shade_w, joint="curve")
        draw.line(pts, fill=color, width=line_w, joint="curve")
        if line_w >= 5:
            offset_pts = [(x - max(1, line_w // 5), y - max(1, line_w // 5)) for x, y in pts]
            draw.line(offset_pts, fill=highlight, width=max(1, line_w // 4), joint="curve")

    resample = getattr(getattr(Image, "Resampling", Image), "LANCZOS", Image.LANCZOS)
    return canvas.resize((width, height), resample)


def _view_angle_degrees(view_name: str) -> float:
    text = str(view_name).lower()
    if "angle" not in text:
        return 0.0
    try:
        return float(text.split("angle", 1)[1].strip().split()[0])
    except (IndexError, ValueError):
        return 0.0


def _apply_scanner_lighting(texture: Image.Image, view_name: str, focused: bool, lighting_settings=None) -> Image.Image:
    """Apply the scanner's image-space lighting to a rendered fabric texture.

    Focused captures call this on one rendered pattern unit before image tiling.
    Full-layout captures may call it on the assembled preview image when that
    preview has not already been lit. Preview and saved images use this same
    function, so the selected lighting mode stays consistent.
    """
    src = texture.convert("RGB")
    arr = np.asarray(src, dtype=np.float32) / 255.0
    if arr.ndim != 3 or arr.shape[0] < 3 or arr.shape[1] < 3:
        return src
    lighting = _normalize_scanner_lighting(lighting_settings)
    if lighting["enabled"] < 0.5:
        return src

    h, w = arr.shape[:2]
    luminance = (
        arr[:, :, 0] * 0.299
        + arr[:, :, 1] * 0.587
        + arr[:, :, 2] * 0.114
    )
    lum_u8 = np.clip(luminance * 255.0, 0, 255).astype(np.uint8)
    smooth_luminance = (
        np.asarray(
            Image.fromarray(lum_u8, "L").filter(ImageFilter.GaussianBlur(lighting["blur"])),
            dtype=np.float32,
        )
        / 255.0
    )
    gy, gx = np.gradient(smooth_luminance)
    relief = lighting["focused_relief"] if focused else lighting["relief"]
    normals = np.dstack((-gx * relief, -gy * relief, np.ones_like(luminance)))
    normals /= np.maximum(np.linalg.norm(normals, axis=2, keepdims=True), 1e-6)

    angle = math.radians(_view_angle_degrees(view_name))
    sun_azimuth = math.radians(lighting["azimuth"])
    sun_elevation = math.radians(lighting["elevation"])
    # A fixed one-sided "sun" in fabric/world coordinates. The camera/fabric
    # view rotates through scan angles while this light stays put, so the same
    # fabric can look slightly different from each viewing angle.
    light_xy = sun_azimuth - angle
    light = np.array(
        [
            math.cos(light_xy) * math.cos(sun_elevation),
            math.sin(light_xy) * math.cos(sun_elevation),
            math.sin(sun_elevation),
        ],
        dtype=np.float32,
    )
    light /= max(float(np.linalg.norm(light)), 1e-6)
    view = np.array([0.0, 0.0, 1.0], dtype=np.float32)
    half_vec = light + view
    half_vec /= max(float(np.linalg.norm(half_vec)), 1e-6)

    diffuse = np.clip(np.sum(normals * light[None, None, :], axis=2), 0.0, 1.0)
    specular = np.clip(np.sum(normals * half_vec[None, None, :], axis=2), 0.0, 1.0) ** 22.0

    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    xx = (xx / max(float(w - 1), 1.0)) - 0.5
    yy = (yy / max(float(h - 1), 1.0)) - 0.5
    directional_falloff = xx * math.cos(light_xy) + yy * math.sin(light_xy)
    broad_light = 1.0 + lighting["shadow"] * directional_falloff
    fabric_gradient = 1.0 + lighting["gradient"] * directional_falloff
    vignette = 1.0 - lighting["vignette"] * np.clip(xx * xx + yy * yy, 0.0, 0.5)

    # Preserve the fabric's actual colors while letting shadows and highlights
    # affect every color equally.
    shade = (lighting["ambient"] + lighting["sun_intensity"] * diffuse) * broad_light * fabric_gradient * vignette
    shade = np.clip(shade, 0.62, 1.16)
    lit = arr * shade[:, :, None]
    lit += specular[:, :, None] * lighting["specular"]

    # Slight view-dependent yarn sheen. It uses the smoothed luminance map so it
    # reads as a soft material response instead of pixel-level sparkle/noise.
    ridge = np.clip((smooth_luminance - np.percentile(smooth_luminance, 42.0)) * 1.65, 0.0, 1.0)
    sheen_axis = angle - sun_azimuth
    sheen_phase = np.sin((xx * math.cos(sheen_axis) + yy * math.sin(sheen_axis)) * math.pi * 5.5)
    sheen = np.clip(sheen_phase, 0.0, 1.0) * ridge * lighting["sheen"]
    lit += sheen[:, :, None]

    out = np.clip(lit * 255.0, 0, 255).astype(np.uint8)
    return Image.fromarray(out, "RGB")


def _lit_rendered_texture_for_camera(plan: FabricPlan, row: int, col: int, focused: bool, view_name: str, camera_zoom: float = 1.0) -> Image.Image | None:
    repeat_rows = max(1, int(plan.pattern_repeat_rows))
    repeat_cols = max(1, int(plan.pattern_repeat_cols))
    spacing_x = float(np.clip(float(getattr(plan, "pattern_repeat_spacing_x", 1.0)), 0.55, 1.45))
    spacing_y = float(np.clip(float(getattr(plan, "pattern_repeat_spacing_y", 1.0)), 0.55, 1.45))
    lighting = _normalize_scanner_lighting(getattr(plan, "scanner_lighting", None))
    lighting_key = tuple((key, round(float(lighting[key]), 4)) for key in sorted(lighting))
    batch_w = int(np.clip(int(getattr(plan, "batch_texture_width", 420)), 160, 2048))
    batch_h = int(np.clip(int(getattr(plan, "batch_texture_height", 340)), 120, 1660))
    camera_zoom = float(np.clip(float(camera_zoom), 0.2, 8.0))
    cache_key = (
        "lit",
        "cell" if focused else "full",
        int(row),
        int(col),
        repeat_rows,
        repeat_cols,
        round(spacing_x, 3),
        round(spacing_y, 3),
        str(view_name),
        bool(focused),
        batch_w,
        batch_h,
        lighting_key,
        round(camera_zoom, 3),
    )
    cache = getattr(plan, "_rendered_texture_cache", None)
    if cache is None:
        cache = {}
        setattr(plan, "_rendered_texture_cache", cache)
    if cache_key not in cache:
        if focused:
            # A fresh, angle-specific real render (real 3D model duplicated,
            # captured, and exact-period tiled -- the Puzzle Mode workflow
            # automated in gui.py) is the primary source when a live renderer
            # is attached: rendered once per (row, col, angle, zoom) and cached
            # here like every other case, so live preview during robot travel
            # does not re-render every frame but a genuinely new angle does.
            #
            # It can decline. The exact-period crop measures the pattern period
            # in screen pixels, which is only meaningful while the fabric is
            # seen roughly face-on; by ~90 degrees the period projects to almost
            # nothing and the crop would collapse to a sliver. Scans use angles
            # of 360*i/n, so with the usual 4 angles 90 and 270 land exactly
            # there. The renderer returns None for those rather than handing
            # back a smear, and the pre-glued seamless tile is used instead.
            render_fn = getattr(plan, "scan_render_capture_fn", None)
            fresh = render_fn(row, col, _view_angle_degrees(view_name), camera_zoom) if render_fn is not None else None

            # Pre-glued per-pattern tiles: already tiled by the repeat sliders
            # and already lit by the real 3D shader, so no further tiling or 2D
            # lighting post-process is applied.
            scan_tiles = getattr(plan, "scan_tiled_pattern_images", None)
            tile_idx = row * plan.grid_cols + col
            if fresh is not None:
                cache[cache_key] = fresh
            elif scan_tiles and 0 <= tile_idx < len(scan_tiles):
                cache[cache_key] = scan_tiles[tile_idx]
            else:
                # Focused scanner captures use the requested workflow:
                # render one selected pattern unit, apply lighting to that unit,
                # then duplicate the lit image by the repeat sliders.
                cell_texture = _render_cell_pattern_texture(plan, row, col, batch_w, batch_h)
                lit_cell = _apply_scanner_lighting(cell_texture, view_name, focused, lighting)
                cache[cache_key] = _tile_rendered_texture(lit_cell, repeat_rows, repeat_cols, spacing_x, spacing_y)
        else:
            texture = _rendered_texture_for_camera(plan, row, col, focused)
            if texture is None:
                return None
            if bool(getattr(plan, "rendered_fabric_image_lit", False)):
                cache[cache_key] = texture
            else:
                cache[cache_key] = _apply_scanner_lighting(texture, view_name, focused, lighting)
    return cache[cache_key]


def _rendered_texture_for_camera(plan: FabricPlan, row: int, col: int, focused: bool) -> Image.Image | None:
    texture = getattr(plan, "rendered_fabric_image", None)
    if texture is not None:
        texture = texture.convert("RGB")
    source_is_full_layout = bool(getattr(plan, "rendered_fabric_image_is_full_layout", False))
    repeat_rows = max(1, int(plan.pattern_repeat_rows))
    repeat_cols = max(1, int(plan.pattern_repeat_cols))
    spacing_x = float(np.clip(float(getattr(plan, "pattern_repeat_spacing_x", 1.0)), 0.55, 1.45))
    spacing_y = float(np.clip(float(getattr(plan, "pattern_repeat_spacing_y", 1.0)), 0.55, 1.45))
    if not focused:
        if texture is None:
            return None
        if source_is_full_layout:
            return texture
        cache_key = ("full", bool(source_is_full_layout), repeat_rows, repeat_cols, round(spacing_x, 3), round(spacing_y, 3))
        cache = getattr(plan, "_rendered_texture_cache", None)
        if cache is None:
            cache = {}
            setattr(plan, "_rendered_texture_cache", cache)
        if cache_key not in cache:
            cache[cache_key] = _tile_rendered_texture(texture, repeat_rows, repeat_cols, spacing_x, spacing_y)
        return cache[cache_key]
    batch_w = int(np.clip(int(getattr(plan, "batch_texture_width", 420)), 160, 2048))
    batch_h = int(np.clip(int(getattr(plan, "batch_texture_height", 340)), 120, 1660))
    cache_key = (
        "cell_direct",
        int(row),
        int(col),
        repeat_rows,
        repeat_cols,
        round(spacing_x, 3),
        round(spacing_y, 3),
        batch_w,
        batch_h,
    )
    cache = getattr(plan, "_rendered_texture_cache", None)
    if cache is None:
        cache = {}
        setattr(plan, "_rendered_texture_cache", cache)
    if cache_key not in cache:
        cell_texture = _render_cell_pattern_texture(plan, row, col, batch_w, batch_h)
        cache[cache_key] = _tile_rendered_texture(cell_texture, repeat_rows, repeat_cols, spacing_x, spacing_y)
    return cache[cache_key]


def draw_scene(
    mujoco,
    handle,
    plan: FabricPlan,
    target_index: int,
    executed: list[np.ndarray],
    camera_enabled: bool = False,
    current_pose: np.ndarray | None = None,
    target_pose: np.ndarray | None = None,
    clear_scene: bool = True,
    simplified: bool = False,
) -> None:
    scn = handle.user_scn
    if clear_scene:
        scn.ngeom = 0

    cell_w = plan.fabric_size[0] / plan.grid_cols
    cell_l = plan.fabric_size[1] / plan.grid_rows
    z = plan.fabric_origin[2] - FABRIC_THICKNESS * 0.5
    fabric_center = plan.fabric_origin + np.array([plan.fabric_size[0] * 0.5, plan.fabric_size[1] * 0.5, 0.0])
    _add_box(
        mujoco,
        scn,
        [fabric_center[0] - 0.12, fabric_center[1], -0.018],
        [0.62, 0.42, 0.012],
        (0.10, 0.105, 0.115, 1.0),
    )
    _add_box(
        mujoco,
        scn,
        [fabric_center[0], fabric_center[1], z - FABRIC_THICKNESS * 0.55],
        [plan.fabric_size[0] * 0.54, plan.fabric_size[1] * 0.54, FABRIC_THICKNESS * 0.16],
        (0.030, 0.036, 0.046, 1.0),
    )
    station_id = plan.station_ids[min(target_index, len(plan.station_ids) - 1)]
    active_cell = plan.station_cells[station_id]
    view_name = plan.view_names[min(target_index, len(plan.view_names) - 1)] if plan.view_names else "angle 0"
    rendered_proxy = _add_rendered_fabric_proxy(mujoco, scn, plan, z, view_name=view_name)
    for row in range(plan.grid_rows):
        for col in range(plan.grid_cols):
            if not rendered_proxy:
                _add_model_cell_fabric(mujoco, scn, plan, row, col, z, highlight=(row, col) == active_cell, simplified=simplified)
            elif (row, col) == active_cell:
                cell_w = plan.fabric_size[0] / plan.grid_cols
                cell_l = plan.fabric_size[1] / plan.grid_rows
                center_x = plan.fabric_origin[0] + cell_w * (col + 0.5)
                center_y = plan.fabric_origin[1] + cell_l * (row + 0.5)
                _add_box(
                    mujoco,
                    scn,
                    [center_x, center_y, z + FABRIC_THICKNESS * 0.28],
                    [cell_w * 0.50, cell_l * 0.50, FABRIC_THICKNESS * 0.08],
                    (0.1, 1.0, 0.3, 0.18),
                )

    _add_batch_result_overlay(mujoco, scn, plan, z, active_cell)

    path_step = max(1, int(math.ceil(len(plan.mapped_points) / 80))) if simplified else 1
    for i in range(0, len(plan.mapped_points) - 1, path_step):
        j = min(i + path_step, len(plan.mapped_points) - 1)
        _add_segment(mujoco, scn, plan.mapped_points[i], plan.mapped_points[j], (0.20, 0.24, 0.30, 0.28), 0.0018)

    if target_index > 0:
        progress_step = max(1, int(math.ceil(target_index / 80))) if simplified else 1
        for i in range(0, min(target_index, len(plan.mapped_points) - 1), progress_step):
            j = min(i + progress_step, len(plan.mapped_points) - 1)
            _add_segment(mujoco, scn, plan.mapped_points[i], plan.mapped_points[j], (0.15, 0.85, 0.35, 0.55), 0.0026)

    trail_limit = min(MAX_TRAIL_POINTS, 60 if simplified else MAX_TRAIL_POINTS)
    trail = executed[-trail_limit:]
    if simplified and len(trail) > 40:
        trail = trail[::max(1, int(math.ceil(len(trail) / 40)))]
    for a, b in zip(trail, trail[1:]):
        _add_segment(mujoco, scn, a, b, (1.00, 0.42, 0.08, 0.90), 0.0032)

    target = plan.mapped_points[min(target_index, len(plan.mapped_points) - 1)]
    station = plan.mapped_stations[station_id]
    color = plan.cell_colors[station_id]
    _add_sphere(mujoco, scn, station, MARKER_RADIUS * 1.15, color)
    _add_sphere(mujoco, scn, target, MARKER_RADIUS * 1.45, (0.1, 1.0, 0.3, 1.0))
    _add_rotation_ring(mujoco, scn, station, min(plan.square_width, plan.square_length) * 0.22, (0.1, 1.0, 0.3, 0.65))
    if target_pose is not None:
        _add_pose_axes(mujoco, scn, target_pose, scale=POSE_AXIS_LENGTH * 1.15, alpha=0.55)
    if current_pose is not None:
        _add_pose_axes(mujoco, scn, current_pose, scale=POSE_AXIS_LENGTH, alpha=0.95)
    if trail:
        _add_sphere(mujoco, scn, trail[-1], MARKER_RADIUS * 1.35, (1.0, 0.42, 0.08, 1.0))
        if camera_enabled:
            _add_camera_marker(mujoco, scn, trail[-1], station)

    handle.sync()


